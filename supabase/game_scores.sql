create table if not exists public.game_scores (
  id bigint generated by default as identity primary key,
  player_name varchar(20) not null,
  score integer not null check (score >= 0 and score <= 999999),
  game_type varchar(20) not null default 'snake',
  created_at timestamptz not null default now()
);

create index if not exists idx_game_scores_game_type_score
  on public.game_scores (game_type, score desc, created_at asc);

alter table public.game_scores enable row level security;

drop policy if exists game_scores_select_all on public.game_scores;
create policy game_scores_select_all
  on public.game_scores
  for select
  using (true);

drop policy if exists game_scores_insert_anon on public.game_scores;
create policy game_scores_insert_anon
  on public.game_scores
  for insert
  with check (
    game_type in ('snake', 'zuma')
    and char_length(player_name) between 1 and 20
    and score >= 0
  );

create table if not exists public.online_status (
  id varchar(64) primary key,
  last_seen timestamptz not null default now()
);

create index if not exists idx_online_status_last_seen
  on public.online_status (last_seen desc);

alter table public.online_status enable row level security;

drop policy if exists online_status_select_all on public.online_status;
create policy online_status_select_all
  on public.online_status
  for select
  using (true);

drop policy if exists online_status_upsert_anon on public.online_status;
create policy online_status_upsert_anon
  on public.online_status
  for insert
  with check (char_length(id) between 1 and 64);

drop policy if exists online_status_update_self on public.online_status;
create policy online_status_update_self
  on public.online_status
  for update
  using (true)
  with check (char_length(id) between 1 and 64);
